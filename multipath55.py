    def plot_avg_costs_by_path_index(self):
        """
        For each monitor cycle, compute the average cost of
        disjoint path #1, #2, and #3 (across only those flows
        where that path was actually found), and plot them as three lines.
        """
        if not self.flow_history:
            return

        # Ordered list of cycles
        cycles = sorted({flow["creation_cycle"] for flow in self.flow_history})

        avg1, avg2, avg3 = [], [], []

        for cycle in cycles:
            # All flows in this cycle
            flows = [f for f in self.flow_history if f["creation_cycle"] == cycle]

            # Collect only finite costs for each path-index
            c1 = [
                f["disjoint_paths"][0][1]
                for f in flows
                if len(f["disjoint_paths"]) >= 1
                   and f["disjoint_paths"][0][1] is not None
                   and math.isfinite(f["disjoint_paths"][0][1])
            ]
            c2 = [
                f["disjoint_paths"][1][1]
                for f in flows
                if len(f["disjoint_paths"]) >= 2
                   and f["disjoint_paths"][1][1] is not None
                   and math.isfinite(f["disjoint_paths"][1][1])
            ]
            c3 = [
                f["disjoint_paths"][2][1]
                for f in flows
                if len(f["disjoint_paths"]) >= 3
                   and f["disjoint_paths"][2][1] is not None
                   and math.isfinite(f["disjoint_paths"][2][1])
            ]

            # Compute per-cycle averages (nan if no successful paths)
            avg1.append(sum(c1) / len(c1) if c1 else float("nan"))
            avg2.append(sum(c2) / len(c2) if c2 else float("nan"))
            avg3.append(sum(c3) / len(c3) if c3 else float("nan"))

        # Plot all three on one axes
        plt.figure(figsize=(10, 6))
        plt.plot(cycles, avg1, marker="o", linestyle="-", label="Path #1")
        plt.plot(cycles, avg2, marker="^", linestyle="-", label="Path #2")
        plt.plot(cycles, avg3, marker="s", linestyle="-", label="Path #3")
        plt.xlabel("Monitor Cycle")
        plt.ylabel("Average Path Cost")
        plt.title("Average Disjoint Path Costs per Cycle (only successful paths)")
        plt.legend()
        plt.grid(True)
        plt.tight_layout()

        # Save it
        plt.savefig("avg_costs_by_path_index.png")
        plt.close()
        self.logger.info(
            "Avg costs by path index plot saved as avg_costs_by_path_index.png"
        )

