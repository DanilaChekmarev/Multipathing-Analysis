#!/usr/bin/env python
"""
Ryu controller that discovers topology and, when a data flow is added,
computes up to 3 disjoint shortest paths for that flow.
You can choose between different path-computation methods:
    - Modified Dijkstra (iterative edge removal)
    - Yen's algorithm
    - A simplified Suurballe algorithm
    - Edge disjoint shortest pair algorithm (computing a disjoint pair plus an extra disjoint path)
    - Bellman-Ford algorithm (iterative disjoint paths using Bellman-Ford)
    - k-shortest paths algorithm by David Eppstein
The algorithm considers link costs and only allows links with sufficient available bandwidth.
The computed flow paths (with their costs and delays) are logged into a text file,
and the topology (with link costs and available bandwidth) is plotted.
Only links defined in link_costs.txt are added.
"""

