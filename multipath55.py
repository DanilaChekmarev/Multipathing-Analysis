class DijkstraController(app_manager.RyuApp):
    OFP_VERSIONS = [ofproto_v1_3.OFP_VERSION]
    # Delay factor (in ms) per unit cost.
    DELAY_PER_HOP = 10
    # Default 50000
    # DragonFly 3000
    # FatTree 5000
    # JellyFish 24000
    DEFAULT_BANDWIDTH = 500

    def __init__(self, *args, **kwargs):
        super(DijkstraController, self).__init__(*args, **kwargs)
        # How many logical CPUs we have; 100% means “all of these fully busy”
        self.cpu_count = psutil.cpu_count(logical=True)
        # Total physical RAM (in bytes)
        self.total_ram = psutil.virtual_memory().total
        # The network topology graph (nodes can be switches or hosts)
        self.net = nx.Graph()
        hub.sleep(20)
        # Mapping for hosts: MAC -> (switch_dpid, port)
        self.hosts = {}
        # Mapping for switch-to-switch links: (src_dpid, dst_dpid) -> out_port
        self.link_ports = {}
        # Load cost mapping from file.
        self.link_costs = {}
        self.load_link_costs()
        hub.sleep(20)
        # Monitoring and plotting history.
        self.monitor_count = 0
        self.available_bw_history = []
        self.monitor_history = []
        self.link_bw_cycle_history = []
        self.avg_path_cost_history = []
        # New: tracking failed path counts
        self.failed_path_count_history = []
        # Active flows and overall flow history.
        self.active_flows = []
        self.flow_history = []
        # Set the algorithm to use.
        # Options: "dijkstra", "yen", "suurballe", "edge_disjoint", "bellman_ford", "eppstein"
        self.path_algorithm = "dijkstra"  # Change as desired.
        # Start a monitoring thread.
        self.monitor_thread = hub.spawn(self._monitor)
        # Initialize/clear the stats file, and write a header + max‐capacity line
        with open("monitor_stats.txt", "w") as f:
            f.write("Cycle | Duration (s) | CPU% | RAM%\n")
            f.write(f"Max   |       —      | 100% = {self.cpu_count}× fully busy | "
                    f"100% = {self.total_ram / (1024**3):.2f} GB total\n\n")

    def _monitor(self):
        """
        Periodically update topology, plots, and add random data flows.
        Also, expire flows older than 5 monitor cycles.
        """
        while self.monitor_count < 25:
            self.monitor_count += 1
            cycle_start = time.time()
            # Initialize failure counter for this cycle
            self.current_cycle_failures = 0

            # === Expire flows older than 5 cycles ===
            expired_flows = []
            for flow in self.active_flows:
                if self.monitor_count - flow["creation_cycle"] >= 5:
                    # restore consumed bandwidth along each of the 3 disjoint paths
                    for path, cost, delay in flow["disjoint_paths"][:3]:
                        for u, v in zip(path, path[1:]):
                            # add back, but don’t exceed the link’s capacity
                            self.net[u][v]['available_bw'] = min(
                                self.net[u][v]['available_bw'] + flow["flow_bw"],
                                self.net[u][v]['bandwidth']
                            )
                    expired_flows.append(flow)
            for flow in expired_flows:
                self.active_flows.remove(flow)
            # =====================================================

            total_avail_bw = sum(data.get('available_bw', 0) for _, _, data in self.net.edges(data=True))
            self.available_bw_history.append(total_avail_bw)
            self.monitor_history.append(self.monitor_count)

            current_link_bws = [data.get('available_bw', 0)
                                      for u, v, data in self.net.edges(data=True)]
            self.link_bw_cycle_history.append(current_link_bws)

            self.plot_topology()
            self.plot_available_bw_over_time()

            self.current_cycle_costs = []
            nodes = list(self.net.nodes())
            if len(nodes) >= 2:
                for _ in range(250):
                    src, dst = random.sample(nodes, 2)
                    flow_bw = random.randint(1, 10)
                    self.add_data_flow(src, dst, flow_bw)

            # Record failure count history
            self.failed_path_count_history.append(self.current_cycle_failures)

            if self.current_cycle_costs:
                avg_cost = sum(self.current_cycle_costs) / len(self.current_cycle_costs)
            else:
                avg_cost = 0
            self.avg_path_cost_history.append(avg_cost)
            self.plot_avg_path_cost_over_time()

            self.plot_cost_boxplot()
            self.plot_bandwidth_boxplot()
            # New: plot failures separately
            self.plot_failed_paths_over_time()
            self.plot_link_bw_boxplot()
            self.plot_link_bw_per_cycle()
            self.plot_avg_costs_by_path_index()
            # Updated combined plot to include failures
            self.plot_combined()

            hub.sleep(5)

            # record end-of-cycle timing and resource usage
            cycle_end = time.time()
            duration = cycle_end - cycle_start
            cpu = psutil.cpu_percent(interval=0.1)
            mem = psutil.virtual_memory().percent

            # append to the same stats file
            self.log_cycle_stats(self.monitor_count, duration, cpu, mem)

            self.logger.info(
                "Monitor cycle %d took %.3fs, CPU: %.1f%%, RAM: %.1f%%",
                self.monitor_count, duration, cpu, mem)


    def log_cycle_stats(self, cycle, duration, cpu, mem):
        """
        Append a line to monitor_stats.txt with:
          Cycle number | duration in seconds | CPU% | RAM%
        """
        with open("monitor_stats.txt", "a") as f:
            f.write(f"{cycle:5d} | {duration:10.3f} | {cpu:5.1f}% | {mem:5.1f}%\n")

    def compute_flow_path(self, src, dst, flow_bw):
        """
        Dispatch the flow path computation to the chosen algorithm.
        Returns up to 3 paths (each a tuple: (path, cost, delay)).
        """
        if self.path_algorithm == "yen":
            return self.compute_flow_path_yen(src, dst, flow_bw)
        elif self.path_algorithm == "suurballe":
            return self.compute_flow_path_suurballe(src, dst, flow_bw)
        elif self.path_algorithm == "edge_disjoint":
            return self.compute_flow_path_edge_disjoint(src, dst, flow_bw)
        elif self.path_algorithm == "bellman_ford":
            return self.compute_flow_path_bellman_ford(src, dst, flow_bw)
        elif self.path_algorithm == "eppstein":    # New option.
            return self.compute_flow_path_eppstein(src, dst, flow_bw)
        else:
            return self.compute_flow_path_dijkstra(src, dst, flow_bw)

    def compute_flow_path_dijkstra(self, src, dst, flow_bw):
        """
        Compute up to 3 disjoint paths using a modified Dijkstra algorithm.
        A temporary graph copy is used and, after finding a path,
        its edges are removed to enforce disjointness.
        """
        def weight_func(u, v, d):
            if d.get('available_bw', 0) < flow_bw:
                return float('inf')
            return d.get('weight', float('inf'))

        disjoint_paths = []
        temp_net = self.net.copy()
        for _ in range(3):
            try:
                path = nx.dijkstra_path(temp_net, src, dst, weight=weight_func)
                cost = nx.dijkstra_path_length(temp_net, src, dst, weight=weight_func)
                delay = cost * self.DELAY_PER_HOP
                disjoint_paths.append((path, cost, delay))
                # Remove edges in the found path.
                for i in range(len(path)-1):
                    if temp_net.has_edge(path[i], path[i+1]):
                        temp_net.remove_edge(path[i], path[i+1])
            except nx.NetworkXNoPath:
                break

        if not disjoint_paths:
            self.logger.info("No available disjoint paths from %s to %s with bandwidth %d",
                             src, dst, flow_bw)
            return None

        with open("shortest_paths.txt", "a") as f:
            for idx, (path, cost, delay) in enumerate(disjoint_paths):
                f.write("Flow from {} to {} (Dijkstra Path {}): {} | Cost: {} | Delay: {} ms | Bandwidth: {} \n".format(
                    src, dst, idx+1, path, cost, delay, flow_bw))
        return disjoint_paths

    def compute_flow_path_yen(self, src, dst, flow_bw):
        """
        Compute exactly 3 fully edge‐disjoint paths using Yen’s k‐shortest simple‐paths,
        by removing each found path’s edges before computing the next.
        Returns [(path, cost, delay), …] or None if fewer than 3 exist.
        """
        try:
            temp = self.net.copy()
            disjoint_paths = []

            for _ in range(3):
                # build a bandwidth‐pruned view of temp
                H = nx.Graph()
                for u, v, data in temp.edges(data=True):
                    if data.get('available_bw', 0) >= flow_bw:
                        H.add_edge(u, v, weight=data['weight'])

                # try to get the next‐shortest simple path
                try:
                    p = next(nx.shortest_simple_paths(H, src, dst, weight='weight'))
                except (nx.NetworkXNoPath, StopIteration):
                    break

                cost = sum(H[u][v]['weight'] for u, v in zip(p, p[1:]))
                delay = cost * self.DELAY_PER_HOP
                disjoint_paths.append((p, cost, delay))

                # remove those edges from temp to enforce disjointness
                for u, v in zip(p, p[1:]):
                    if temp.has_edge(u, v):
                        temp.remove_edge(u, v)

            if len(disjoint_paths) < 3:
                return None

            with open("shortest_paths.txt", "a") as f:
                for idx, (p, c, d) in enumerate(disjoint_paths, start=1):
                    f.write(f"Flow from {src} to {dst} (Yen Path {idx}): {p} | "
                            f"Cost: {c} | Delay: {d} ms | BW: {flow_bw}\n")

            return disjoint_paths

        except Exception as e:
            self.logger.error("Yen error %s→%s (bw=%d): %s", src, dst, flow_bw, e)
            return None

    def compute_flow_path_suurballe(self, src, dst, flow_bw):
        """
        Compute up to 3 edge-disjoint paths using Suurballe's algorithm.
        """
        try:
            # Build directed subgraph H with only edges that can carry the flow
            H = nx.DiGraph()
            for u, v, data in self.net.edges(data=True):
                if data.get('available_bw', 0) >= flow_bw:
                    w = data.get('weight', float('inf'))
                    H.add_edge(u, v, weight=w)
                    H.add_edge(v, u, weight=w)

            # Early exit if no path exists
            if not nx.has_path(H, src, dst):
                self.logger.info("No available Suurballe paths from %s to %s (bw=%d)", src, dst, flow_bw)
                return None

            # Primary shortest path
            path1 = nx.dijkstra_path(H, src, dst, weight='weight')
            cost1 = nx.dijkstra_path_length(H, src, dst, weight='weight')

            # Reweight edges
            dist = nx.single_source_dijkstra_path_length(H, src, weight='weight')
            H_r = nx.DiGraph()
            for u, v, d in H.edges(data=True):
                if u in dist and v in dist:
                    new_w = d['weight'] + dist[u] - dist[v]
                    H_r.add_edge(u, v, weight=new_w)

            # Remove both directions of path1 from H_r to enforce edge-disjointness
            for u, v in zip(path1, path1[1:]):
                if H_r.has_edge(u, v):
                    H_r.remove_edge(u, v)
                if H_r.has_edge(v, u):
                    H_r.remove_edge(v, u)

            # Second shortest path in residual
            try:
                path2 = nx.dijkstra_path(H_r, src, dst, weight='weight')
                # Compute real cost on original H
                cost2 = sum(H[path2[i]][path2[i+1]]['weight'] for i in range(len(path2)-1))
            except nx.NetworkXNoPath:
                path2, cost2 = None, None

            suurballe_paths = [(path1, cost1, cost1 * self.DELAY_PER_HOP)]
            if path2 is not None:
                suurballe_paths.append((path2, cost2, cost2 * self.DELAY_PER_HOP))

            # Third path: simple disjoint by removing both directions of first two paths
            temp = self.net.copy()
            for p in [path1] + ([path2] if path2 else []):
                for u, v in zip(p, p[1:]):
                    if temp.has_edge(u, v): temp.remove_edge(u, v)
                    if temp.has_edge(v, u): temp.remove_edge(v, u)

            def wf(u, v, d):
                return d['weight'] if d.get('available_bw', 0) >= flow_bw else float('inf')

            try:
                path3 = nx.dijkstra_path(temp, src, dst, weight=wf)
                cost3 = nx.dijkstra_path_length(temp, src, dst, weight=wf)
                suurballe_paths.append((path3, cost3, cost3 * self.DELAY_PER_HOP))
            except nx.NetworkXNoPath:
                pass

            if not suurballe_paths:
                self.logger.info(
                    "No valid Suurballe paths from %s to %s (bw=%d)", src, dst, flow_bw
                )
                return None

            # Log and return
            with open("shortest_paths.txt", "a") as f:
                for idx, (p, c, d) in enumerate(suurballe_paths, start=1):
                    f.write(
                        f"Suurballe from {src} to {dst} (Path {idx}): {p} | "
                        f"Cost: {c} | Delay: {d} ms | Bandwidth: {flow_bw}\n"
                    )
            return suurballe_paths

        except Exception as e:
            self.logger.error(
                "Error computing Suurballe paths from %s to %s (bw=%d): %s",
                src, dst, flow_bw, e
            )
            return None

    def compute_flow_path_edge_disjoint(self, src, dst, flow_bw):
        """
        Compute up to 3 disjoint paths using an edge‐disjoint approach,
        pre‐filtering by bandwidth and catching errors to continue execution.
        """
        try:
            # Build pruned graph G with only edges that can carry the flow
            G = nx.Graph()
            for u, v, data in self.net.edges(data=True):
                if data.get('available_bw', 0) >= flow_bw:
                    G.add_edge(u, v, weight=data.get('weight', float('inf')))

            # Early exit if no path exists
            if not nx.has_path(G, src, dst):
                self.logger.info(
                    "No available edge‐disjoint paths from %s to %s (bw=%d)",
                    src, dst, flow_bw
                )
                return None

            paths = []
            # Path 1
            path1 = nx.dijkstra_path(G, src, dst, weight='weight')
            cost1 = nx.dijkstra_path_length(G, src, dst, weight='weight')
            delay1 = cost1 * self.DELAY_PER_HOP
            paths.append((path1, cost1, delay1))

            # Path 2: remove path1 edges
            G2 = G.copy()
            for u, v in zip(path1, path1[1:]):
                if G2.has_edge(u, v):
                    G2.remove_edge(u, v)
            try:
                path2 = nx.dijkstra_path(G2, src, dst, weight='weight')
                cost2 = nx.dijkstra_path_length(G2, src, dst, weight='weight')
                delay2 = cost2 * self.DELAY_PER_HOP
                paths.append((path2, cost2, delay2))
            except nx.NetworkXNoPath:
                path2 = None

            # Path 3: remove path2 edges too
            G3 = G2.copy()
            if path2:
                for u, v in zip(path2, path2[1:]):
                    if G3.has_edge(u, v):
                        G3.remove_edge(u, v)
            try:
                path3 = nx.dijkstra_path(G3, src, dst, weight='weight')
                cost3 = nx.dijkstra_path_length(G3, src, dst, weight='weight')
                delay3 = cost3 * self.DELAY_PER_HOP
                paths.append((path3, cost3, delay3))
            except nx.NetworkXNoPath:
                pass

            # Log and return
            with open("shortest_paths.txt", "a") as f:
                for idx, (p, c, d) in enumerate(paths, start=1):
                    f.write(
                        f"Edge-Disjoint from {src} to {dst} (Path {idx}): {p} | "
                        f"Cost: {c} | Delay: {d} ms | Bandwidth: {flow_bw}\n"
                    )
            return paths

        except Exception as e:
            self.logger.error(
                "Error computing edge‐disjoint paths from %s to %s (bw=%d): %s",
                src, dst, flow_bw, e
            )
            return None

    def compute_flow_path_bellman_ford(self, src, dst, flow_bw):
        """
        Compute up to 3 disjoint paths using the Bellman-Ford algorithm.
        A temporary graph copy is used and, after finding a path,
        its edges are removed to enforce disjointness.
        """
        def weight_func(u, v, d):
            if d.get('available_bw', 0) < flow_bw:
                return float('inf')
            return d.get('weight', float('inf'))

        disjoint_paths = []
        temp_net = self.net.copy()
        for _ in range(3):
            try:
                path = nx.bellman_ford_path(temp_net, src, dst, weight=weight_func)
                cost = nx.bellman_ford_path_length(temp_net, src, dst, weight=weight_func)
                delay = cost * self.DELAY_PER_HOP
                disjoint_paths.append((path, cost, delay))
                for i in range(len(path)-1):
                    if temp_net.has_edge(path[i], path[i+1]):
                        temp_net.remove_edge(path[i], path[i+1])
            except nx.NetworkXNoPath:
                break

        if not disjoint_paths:
            self.logger.info("No available disjoint paths from %s to %s with bandwidth %d (Bellman-Ford)",
                             src, dst, flow_bw)
            return None

        with open("shortest_paths.txt", "a") as f:
            for idx, (path, cost, delay) in enumerate(disjoint_paths):
                f.write("Flow from {} to {} (Bellman-Ford Path {}): {} | Cost: {} | Delay: {} ms | Bandwidth: {} \n".format(
                    src, dst, idx+1, path, cost, delay, flow_bw))
        return disjoint_paths

    def compute_flow_path_eppstein(self, src, dst, flow_bw):
        """
        Compute exactly 3 fully edge‐disjoint paths using an iterative
        k‐shortest simple paths approach, removing each found path’s edges.
        Returns [(path, cost, delay), …] or None if fewer than 3 exist.
        """
        try:
            temp = self.net.copy()
            disjoint_paths = []

            for _ in range(3):
                H = nx.Graph()
                for u, v, data in temp.edges(data=True):
                    if data.get('available_bw', 0) >= flow_bw:
                        H.add_edge(u, v, weight=data['weight'])
                if not nx.has_path(H, src, dst):
                    break

                try:
                    p = next(nx.shortest_simple_paths(H, src, dst, weight='weight'))
                except StopIteration:
                    break

                cost = sum(H[u][v]['weight'] for u, v in zip(p, p[1:]))
                delay = cost * self.DELAY_PER_HOP
                disjoint_paths.append((p, cost, delay))

                for u, v in zip(p, p[1:]):
                    if temp.has_edge(u, v):
                        temp.remove_edge(u, v)

            if len(disjoint_paths) < 3:
                return None

            with open("shortest_paths.txt", "a") as f:
                for idx, (p, c, d) in enumerate(disjoint_paths, start=1):
                    f.write(f"Flow from {src} to {dst} (Eppstein Path {idx}): {p} | "
                            f"Cost: {c} | Delay: {d} ms | BW: {flow_bw}\n")

            return disjoint_paths

        except Exception as e:
            self.logger.error("Eppstein error %s→%s (bw=%d): %s", src, dst, flow_bw, e)
            return None

    def load_link_costs(self):
        """
        Load link costs from 'link_costs.txt'.
        Each line should be in the format: <src> <dst> <cost>
        (Switch names are assumed to be in the form 's<ID>').
        """
        self.link_costs = {}
        try:
            with open('link_costs.txt', 'r') as f:
                for line in f:
                    src, dst, cost = line.strip().split()
                    src_id = int(src[1:])
                    dst_id = int(dst[1:])
                    key = frozenset({src_id, dst_id})
                    self.link_costs[key] = int(cost)
            self.logger.info("Loaded link costs: %s", self.link_costs)
        except Exception as e:
            self.logger.error("Failed to load link_costs.txt: %s", e)

    def plot_topology(self):
        """
        Plot the network topology with edge labels showing link costs and available bandwidth.
        Also, display the current number of active flows.
        """
        plt.figure(figsize=(10, 10))
        pos = nx.spring_layout(self.net, seed=42)
        node_size = 100
        labels = {node: str(node) for node in self.net.nodes()}
        nx.draw_networkx_nodes(self.net, pos, node_color='lightblue', node_size=node_size)
        nx.draw_networkx_labels(self.net, pos, labels=labels, font_size=8)
        edge_colors = []
        for u, v, data in self.net.edges(data=True):
            avail_bw = data.get('available_bw', 0)
            normalized = avail_bw / self.DEFAULT_BANDWIDTH
            color = (1 - normalized, normalized, 0)
            edge_colors.append(color)
        nx.draw_networkx_edges(self.net, pos, edgelist=list(self.net.edges()),
                               edge_color=edge_colors, width=2)
        active_flow_count = len(self.active_flows)
        plt.text(0.05, 0.95, f"Active Flows: {active_flow_count}",
                 transform=plt.gca().transAxes, fontsize=12,
                 verticalalignment='top',
                 bbox=dict(facecolor='white', alpha=0.8, boxstyle='round'))
        plt.title("Network Topology with Available Bandwidth")
        plt.tight_layout()
        plt.savefig("topology.png")
        plt.close()
        self.logger.info("Topology plot saved as topology.png")

