    def plot_cost_boxplot(self):
        """
        Create a single figure with three box-plots—one for each
        disjoint path (1st, 2nd, 3rd)—all sharing the same y-axis.
        """
        if not self.flow_history:
            return

        # Gather costs by path index
        costs_by_path = {1: [], 2: [], 3: []}
        for flow in self.flow_history:
            for idx, (_, cost, _) in enumerate(flow.get("disjoint_paths", []), start=1):
                if idx in costs_by_path and cost is not None:
                    costs_by_path[idx].append(cost)

        # If there's no data at all, bail out
        if not any(costs_by_path.values()):
            return

        # Set up 1×3 subplots, sharing the y-axis
